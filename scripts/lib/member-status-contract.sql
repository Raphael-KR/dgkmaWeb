  -- The row lock serializes app and office CLI changes. Baseline rows never pass through this trigger.
  CREATE FUNCTION public.record_membership_change() RETURNS trigger
  LANGUAGE plpgsql SET search_path = pg_catalog AS $body$
  DECLARE
    prior text;
    event_type text;
  BEGIN
    IF TG_OP = 'INSERT' THEN
      IF NEW.membership_history IS DISTINCT FROM '[]'::jsonb THEN
        RAISE EXCEPTION 'Initial membership history must be empty';
      END IF;
      prior := '미가입';
    ELSE
      IF NEW.membership_history IS DISTINCT FROM OLD.membership_history THEN
        RAISE EXCEPTION 'Membership history is generated by status transitions';
      END IF;
      prior := OLD.alumni_status;
    END IF;
    IF prior = '사망' AND NEW.alumni_status <> prior THEN
      RAISE EXCEPTION 'Deceased alumni cannot be reactivated';
    END IF;
    IF NEW.alumni_status = '사망' THEN
      NEW.is_verified := false;
      NEW.is_admin := false;
      NEW.kakao_sync_enabled := false;
    END IF;
    IF NEW.alumni_status = prior THEN RETURN NEW; END IF;
    event_type := CASE
      WHEN NEW.alumni_status = '사망' THEN '사망 기록'
      WHEN NEW.alumni_status = '가입 완료' AND prior IN ('미가입','가입 대기','동문회 탈퇴자') THEN '가입 확정'
      WHEN NEW.alumni_status = '가입 대기' AND prior = '가입 완료' THEN '승인 취소'
      WHEN NEW.alumni_status = '가입 대기' AND prior = '가입 거부' THEN '재심사'
      WHEN NEW.alumni_status = '가입 대기' AND prior = '미가입' THEN '가입 신청'
      WHEN NEW.alumni_status = '가입 거부' AND prior IN ('미가입','가입 대기') THEN '가입 거부'
      WHEN NEW.alumni_status = '미가입' AND prior = '가입 거부' THEN '거부 신청 삭제'
      WHEN NEW.alumni_status = '동문회 탈퇴자' AND prior = '가입 완료' THEN '탈퇴원 접수'
    END;
    IF event_type IS NULL THEN RAISE EXCEPTION 'Invalid membership transition'; END IF;
    NEW.membership_history := NEW.membership_history || jsonb_build_array(jsonb_build_object(
      'type', event_type, 'at', CASE WHEN event_type = '탈퇴원 접수'
        THEN transaction_timestamp() ELSE clock_timestamp() END));
    IF TG_OP = 'UPDATE' AND NEW.alumni_status = '사망' THEN
      DELETE FROM public.session WHERE sess ->> 'userId' = NEW.id::text;
    END IF;
    RETURN NEW;
  END
  $body$;
  CREATE TRIGGER users_record_membership_change
    BEFORE INSERT OR UPDATE OF alumni_status, membership_history, is_verified, is_admin, kakao_sync_enabled
    ON public.users FOR EACH ROW EXECUTE FUNCTION public.record_membership_change();
